// Retrieves only the incomplete tasks for a specific user from 'tasks'.
// Takes uuid and returns tasks where completed is false.
export const getIncompleteTasks = async (uuid: string) => {
  try {
      const { data, error } = await supabase
          .from("tasks")
          .select("taskID, taskCategory, taskName, dueDate")
          .eq("uuid", uuid)
          .eq("completed", false);

      if (error) {
          console.error("Error fetching incomplete tasks:", error.message);
          return [];
      }

      return data.sort(
          (a, b) => new Date(a.dueDate).getTime() - new Date(b.dueDate).getTime()
      );
  } catch (error) {
      console.error("Unexpected error fetching tasks:", error);
      return [];
  }
};

