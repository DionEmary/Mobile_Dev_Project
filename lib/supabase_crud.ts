import supabase from './supabase';

// Get all the user details so it can be used by multiple other functions who only need a few of the details
export async function getUserDetails() {
    try {
        const { data: authUser, error: authError } = await supabase.auth.getUser();
        if (authError || !authUser?.user) {
            throw new Error('Error fetching authenticated user');
        }

        const userId = authUser.user.id;
        const { data: userDetails, error: userDetailsError } = await supabase
            .from('user_details')
            .select('firstName, lastName, email, userNote, userGoal, autoDelete, autoDeleteDays')
            .eq('uuid', userId)
            .single();

        if (userDetailsError) {
            throw new Error('Error fetching user details');
        }

        return { ...userDetails, uuid: userId };
    } catch (error) {
        console.error(error);
        return null;
    }
}

